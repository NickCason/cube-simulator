// things in the world they call to mind. Blue and green swirled is the
// Earth from space; red, orange and yellow up the cube is a Tequila
// Sunrise; yellow in the middle with white round it, a fried egg; red with
// white spots, a toadstool. (See namegen.js matchThemes.)
//
// Each: s - the shapes it's seen in ('free', 'up', 'core', 'shell', 'rings',
// 'across', 'corner', 'tiles' - tiles any shape with more than one tile -
// or 'any'); r - its colours (roles), each one some colour of the cube
// must be; opt - colours it may have too. A role: a family (red orange
// yellow green teal blue purple pink brown white grey black), or a kind -
// warm cool neutral bright cream gold navy mint sky tan rust olive any -
// with :L light, :D dark, :M mid, :V vivid, :P pale; alternatives with |.
// (Tiled - a little cube of the gradient each: radial or cubial, a dot
// each ('dots'); up, across, corner, stripes, as many again; freeform or
// rings, a motif each ('tiles').)
// o: the roles are in order (up the cube; from the middle out; one side to
// the other) - f: either way round. b: its Blend, [min, max]; rep: its
// repeats (an ordered one: just once, unless it says); cn: how many
// colours; t: tiles at least; dom: the role that's most of it; few: one
// that's only a little of it; pastel: mostly pastels; bold: not; muted: no
// loud ones; m: materials it's all the more for; n (names), a
// (adjectives), k (nouns: what to call it, with a word of the cube's own:
// "Bouncy Lava Lamp").

