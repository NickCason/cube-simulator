import { defineConfig } from 'vite';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

// The service worker (offline play, install as an app): written at build time
// with the exact files of this build to keep, under a cache named for them.
// Pages: network first (a new version shows up when online), the cached
// shell when not. Everything else: cache first (the bundle's names are
// content hashes; the rest is small and rarely changes).
function serviceWorker() {
  const listPublic = (dir, root = dir) =>
    readdirSync(dir).flatMap((f) => {
      const p = join(dir, f);
      return statSync(p).isDirectory() ? listPublic(p, root) : [relative(root, p).split('\\').join('/')];
    });
  return {
    name: 'cube-sim-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const pub = listPublic('public');
      const files = ['./', ...Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'index.html'), ...pub].map((f) => (f === './' ? f : './' + f));
      // (named for everything it holds: the page, the bundle, the public files)
      const h = createHash('sha1').update(files.join('\n')).update(readFileSync('index.html'));
      for (const f of pub) h.update(readFileSync(join('public', f)));
      const version = 'cube-sim-' + h.digest('hex').slice(0, 10);
      const source = `// generated by vite.config.js
const CACHE = ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('cube-sim-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put('./', copy));
          }
          return res;
        })
        .catch(() => caches.match('./')),
    );
    return;
  }
  e.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

export default defineConfig({
  base: './',
  build: {
    target: 'es2020',
    chunkSizeWarningLimit: 1200,
  },
  plugins: [serviceWorker()],
  server: { allowedHosts: true },
});
